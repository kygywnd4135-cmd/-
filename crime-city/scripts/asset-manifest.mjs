// Generates app/lib/asset-manifest.ts: every preloadable public asset grouped by the
// screen ("section") that needs it, with its byte size so the loading screen can
// report real progress. Runs before every build; rerun after adding assets.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = path.join(root, 'public');
const SECTION_BY_FOLDER = {start: 'start', story: 'story', office: 'office', event: 'event'};
const IMAGE = /\.(png|jpe?g|webp|svg|gif|avif)$/i;
const SKIP = new Set(['assets/loading-character.webp']);
const SECTION_BY_FILE = {'assets/crime-city-logo.webp': 'start'};

const sections = {start: [], story: [], lobby: [], office: [], event: []};
function walk(dir) {
  for (const entry of fs.readdirSync(dir, {withFileTypes: true}).sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) { walk(full); continue; }
    const rel = path.relative(publicDir, full).split(path.sep).join('/');
    if (!IMAGE.test(rel) || SKIP.has(rel)) continue;
    const folder = rel.split('/')[1];
    const section = SECTION_BY_FILE[rel] ?? (rel.split('/').length > 2 ? SECTION_BY_FOLDER[folder] ?? 'lobby' : 'lobby');
    sections[section].push(['/' + rel, fs.statSync(full).size]);
  }
}
walk(path.join(publicDir, 'assets'));
const fonts = [['/fonts/SUITE-Variable.woff2', fs.statSync(path.join(publicDir, 'fonts/SUITE-Variable.woff2')).size]];
const out = `// Generated by scripts/asset-manifest.mjs. Do not edit by hand.
export type LoadSection='start'|'story'|'lobby'|'office'|'event';
export const ASSET_MANIFEST:Record<LoadSection,[string,number][]>=${JSON.stringify(sections)};
export const FONT_MANIFEST:[string,number][]=${JSON.stringify(fonts)};
`;
fs.writeFileSync(path.join(root, 'app/lib/asset-manifest.ts'), out);
console.log('asset manifest:', Object.entries(sections).map(([k, v]) => `${k} ${v.length} files ${Math.round(v.reduce((a, x) => a + x[1], 0) / 1024)}KB`).join(', '));
